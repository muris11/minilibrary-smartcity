    <!-- Abstract -->
    <h3>Abstract</h3>
    <p>
        The paper examines how environment-related smart city capabilities are forming in two cities—Lyon (France)
        and Bandar Lampung (Indonesia). Using qualitative interviews with government officials and a five-point Likert
        survey of stakeholders,
        the study finds that Lyon is more advanced, thanks in part to private sector participation and integrated
        systems. Bandar Lampung, by contrast,
        is consolidating foundational elements and exhibits early-stage adoption across several subdomains. The article
        concludes with recommendations for
        scaling sustainable, data-enabled services that align technology and social dimensions.
    </p>

    <!-- Key Findings (styled simply like intro content) -->
    <h3>Key Findings at a Glance</h3>
    <p>
    <ul style="margin-left:1.2rem;">
        <li><strong>Lyon</strong>: mature environment-related practices, stronger private sector engagement, better
            integration of sensing, analytics, and service delivery.</li>
        <li><strong>Bandar Lampung</strong>: readiness and partial adoption visible (e.g., sustainability principles,
            pollution monitoring), with gaps in scale, standardization, and accessibility.</li>
        <li><strong>Priority subdomains for Lampung</strong>: buildings &amp; housing; pollution control; renewable
            energy &amp; smart grids; water &amp; waste management; public space greening.</li>
    </ul>
    </p>

    <!-- Scope & Indicators -->
    <h3>Scope &amp; Indicators (Environment-Related Domain)</h3>
    <p>
        The environment-related domain—following Yin et&nbsp;al. (2015)—covers eight subdomains used in the Lampung
        assessment:
    </p>
    <ul style="margin-left:1.2rem;">
        <li><strong>Public Space</strong> (green belts, parks, ecological corridors, liveability, and environmental
            impact).</li>
        <li><strong>Buildings</strong> (sustainable design, energy performance, networked/organized building layouts).
        </li>
        <li><strong>Housing</strong> (smart-home readiness, renewable use in households, accessibility for people with
            disabilities, greenery integration).</li>
        <li><strong>Pollution Control</strong> (regulations, monitoring networks, community use of environmental tech,
            integrated environmental management).</li>
        <li><strong>Renewable Energy</strong> (share and practicality of renewable sources in urban use).</li>
        <li><strong>Smart Grid</strong> (metering, grid efficiency, demand response, integration of distributed
            generation).</li>
        <li><strong>Water Management</strong> (quality monitoring, distribution control, contamination risk mitigation).
        </li>
        <li><strong>Waste Management</strong> (smart bins, collection routing, analytics-driven operational efficiency).
        </li>
    </ul>

