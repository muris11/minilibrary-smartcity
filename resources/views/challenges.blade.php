    <!-- Gaps & Enablers -->
    <h3>Gaps &amp; Enablers for Lampung</h3>
    <ul style="margin-left:1.2rem;">
        <li><strong>Scale &amp; Standardization</strong>: citywide programs for ZEB, smart-home baselines, and
            accessibility codes.</li>
        <li><strong>Data Capability</strong>: end-to-end pipeline from sensors → analytics → public dashboards →
            operational response.</li>
        <li><strong>Multi-Stakeholder Collaboration</strong>: PPPs to mobilize private sector expertise and financing.
        </li>
        <li><strong>Regulatory Alignment</strong>: interoperable data policies, privacy/security, performance-based
            procurement.</li>
    </ul>

    <!-- Roadmap -->
    <h3>Suggested Implementation Roadmap for Lampung</h3>
    <ul style="margin-left:1.2rem;">
        <li><strong>0–12 months (Foundations)</strong>: city data unit; air-quality & microclimate sensors + public
            dashboard; ZEB/retrofit studies; accessibility baselines; smart-bin pilot.</li>
        <li><strong>12–24 months (Integration)</strong>: scale sensors + event-based alerts; rooftop PV at public
            facilities; smart meters & demand-response pilots; green corridors with IoT probes; smart-home starter kits;
            enforced accessibility checklists.</li>
        <li><strong>24–36 months (Scale &amp; Optimization)</strong>: expand ZEB retrofits; citywide smart-bin & dynamic
            routing; unified ops view for energy/water/waste; predictive maintenance; annual Smart Environment Report
            with KPIs.</li>
    </ul>

    <!-- KPIs -->
    <h3>Indicative KPIs &amp; Data Sources</h3>
    <ul style="margin-left:1.2rem;">
        <li><strong>Buildings/Housing</strong>: kWh/m²/year, % ZEB/near-ZEB, # accessible units, % homes with smart-home
            kits.</li>
        <li><strong>Pollution</strong>: PM<sub>2.5</sub>/NO<sub>2</sub> annual mean, % WHO-compliant days, # sensors
            online, response time to alerts.</li>
        <li><strong>Renewables/Smart Grid</strong>: % renewable electricity, # smart meters, demand-response
            participation.</li>
        <li><strong>Water</strong>: % samples within thresholds, NRW %, # auto-detected anomalies.</li>
        <li><strong>Waste</strong>: km reduced via dynamic routing, missed-pickup rate, fill-level compliance, diversion
            rate.</li>
        <li><strong>Public Space</strong>: added green corridor hectares, canopy cover %, heat island reduction (°C).
        </li>
    </ul>

    <!-- Risks -->
    <h3>Risks &amp; Mitigations</h3>
    <ul style="margin-left:1.2rem;">
        <li><strong>Fragmented systems</strong> → open standards, shared data models, inter-agency SLAs.</li>
        <li><strong>Funding constraints</strong> → phased PPPs, performance-based contracts, climate/SDG-aligned grants.
        </li>
        <li><strong>Low adoption</strong> → community co-design, incentives, transparent dashboards.</li>
        <li><strong>Data/privacy concerns</strong> → privacy-by-design, consent flows, audits, cybersecurity drills.
        </li>
    </ul>
