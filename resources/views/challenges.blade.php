    <!-- Methods -->
    <h3>Study Design &amp; Methods</h3>
    <ul style="margin-left:1.2rem;">
        <li><strong>Design</strong>: qualitative comparison between Lyon and Bandar Lampung—both regional economic
            drivers.</li>
        <li><strong>Data Collection</strong>:
            <ul style="margin-left:1.2rem;">
                <li>Interviews with city officials responsible for urban development to assess environment-related
                    indicators.</li>
                <li>Five-point Likert surveys completed by city administrations and the public.</li>
                <li>Pilot testing of the questionnaire for clarity and length; triangulation via report-backs to
                    informants to ensure authenticity.</li>
                <li>Secondary sources: official websites, documents, and related datasets where available.</li>
            </ul>
        </li>
        <li><strong>Analysis</strong>:
            <ul style="margin-left:1.2rem;">
                <li>Descriptive coding and categorization of interview transcripts to extract patterns across
                    subdomains.</li>
                <li>Descriptive statistics (SPSS) to summarize stakeholder perceptions for each indicator set.</li>
            </ul>
        </li>
    </ul>

    <!-- Findings -->
    <h3>Findings for Bandar Lampung (Environment-Related Domain)</h3>
    <p>
        The survey and interviews indicate that Bandar Lampung is in a <em>preparatory/maturation</em> phase. Several
        elements are present or
        emerging, while others require scaling, standardization, and stronger governance or private-sector
        collaboration.
    </p>
    <ul style="margin-left:1.2rem;">
        <li><strong>Buildings</strong>: sustainability principles and organized building networks are acknowledged;
            <em>Zero-Energy Building</em> remains uncommon.
        </li>
        <li><strong>Housing</strong>: greenery and pleasant environments are strong; renewables are used unevenly;
            smart-home features and disability accessibility need scaling.</li>
        <li><strong>Pollution Control</strong>: regulations and monitoring exist; technology detects excessive
            pollution; integrated environmental management is recognized; community-led data stewardship can expand.
        </li>
        <li><strong>Renewable Energy &amp; Smart Grid</strong>: adoption signals exist, but systemic integration (smart
            meters, DR, coordination of distributed generation) is nascent.</li>
        <li><strong>Public Space</strong>: micro-level greening is visible; city-scale green corridors and IoT sensing
            can be consolidated.</li>
        <li><strong>Water Management</strong>: sensor-based monitoring and distribution control are priority areas for
            strengthening.</li>
        <li><strong>Waste Management</strong>: smart bins, fill-level analytics, and dynamic routing are opportunities
            rather than widespread practice.</li>
    </ul>

