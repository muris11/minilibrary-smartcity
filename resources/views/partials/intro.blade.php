        <div class="content-grid">
            <div class="content-item">
                <h3>Definition of Smart City</h3>
                <p>A Smart City is an urban area that leverages digital technologies, data analytics, and interconnected
                    systems to improve the quality of life for residents, optimize city operations, and promote
                    sustainable development. It integrates information and communication technologies (ICT), Internet of
                    Things (IoT), big data, and artificial intelligence (AI) to enhance urban infrastructure, including
                    transportation networks, water and energy management, waste disposal, and public safety.</p>

                <div class="image-container">
                    <img src="{{ asset('images/bg1.png') }}" alt="Smart City" class="responsive-image">
                </div>
            </div>

            <div class="content-item">
                <h3>Key Characteristics</h3>
                <p>Smart cities leverage technology to improve the overall standard of living. Examples include
                    Singapore's Smart Nation initiative, Barcelona's smart lighting and waste management systems, and
                    Jakarta's "Jakarta Kini (JAKI)" platform, which enhances citizen engagement and public service
                    delivery.</p>

                <div class="image-container">
                    <img src="{{ asset('images/bg2.png') }}" alt="Smart City Infrastructure" class="responsive-image">
                </div>
            </div>
        </div>

        <div class="content-full">
            <h3>Technology Integration</h3>
            <p>In a smart city, IoT devices, sensors, and real-time data analytics are widely used to monitor and manage
                infrastructure. These technologies enable city administrators to make proactive decisions, reduce
                congestion, lower energy consumption, and improve overall urban livability.</p>
        </div>
    </div>

