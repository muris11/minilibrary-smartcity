        <h1>Supporting Technologies for Smart City</h1>

        <div class="modern-image-container">
            <img src="{{ asset('images/tech.png') }}" alt="Smart City Technologies" class="modern-image">
        </div>

        <p>
            The study emphasizes an <strong>Internet of Things (IoT) and Big Data architecture</strong> that links
            distributed devices and sensors across the city to continuously collect environmental data for
            <em>planning and decision-making</em>. A citywide network of connected devices enables officials to monitor
            key indicators (e.g., emissions, humidity, microclimate) and feed analytics dashboards that inform
            proactive interventions and long-term urban planning.
        </p>

        <p>
            In the built environment, <strong>smart homes</strong> and energy-aware buildings are highlighted as
            foundations for environmental gains. Smart-home capabilities (pervasive computing within the dwelling)
            enable residents to monitor and reduce energy consumption, while building management systems optimize
            heating, cooling, and lighting based on occupancy and weather patterns.
        </p>

        <p>
            <strong>Pollution monitoring systems</strong> combine video analytics with ambient sensors to track air
            quality,
            noise levels, and traffic emissions in real-time. These systems provide early warning capabilities and help
            city planners identify pollution hotspots for targeted interventions.
        </p>

        <p>
            <strong>Renewable energy integration</strong> with smart grid technology allows cities to optimize energy
            distribution and storage. Solar panels, wind turbines, and energy storage systems work together through
            intelligent management systems to reduce carbon footprint and improve energy security.
        </p>

        <p>
            <strong>Water quality monitoring</strong> and distribution control systems use sensor networks to detect
            leaks, monitor water quality, and optimize distribution pressure. These systems help conserve water
            resources and ensure safe drinking water for all residents.
        </p>

        <p>
            <strong>Smart waste management</strong> utilizes intelligent containers with fill-level sensors that
            notify operators before overflow, coupled with <em>route optimization</em> algorithms to increase collection
            efficiency. This pairing cuts operational costs and emissions while keeping streets cleaner—especially in
            dense or visitor-heavy areas.
        </p>
    </div>

